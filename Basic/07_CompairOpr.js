// Comparision Operators

 let a = 10;
 let b = "10";
 console.log(a == b); 
 console.log(a === b); 
 console.log(a != b); 
 console.log(a !== b); 
 console.log(a > b); 
 console.log(a < b); 
 console.log(a >= b); 
 console.log(a <= b); 

 //Asignment Operators
let num = 10;
console.log(num); 
console.log(num += 5); 
console.log(num -= 5); 
console.log(num *= 5); 
console.log(num /= 5); 
console.log(num %= 5);
console.log(num **= 5); 